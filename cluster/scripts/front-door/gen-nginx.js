// Writes the nginx server blocks for a bridge front door to stdout: an HTTP block for the Let's Encrypt challenge and one
// TLS block per node, each proxying PLAIN WebSocket to that node's relay port (relay.js), which dials the node's user port.
// It is the dev front door's proven pattern (nginx-bridge-dev.blumefi.com.conf) for any number of nodes and any hostname.
// It only prints: nothing is installed or reloaded. Review the output, then see README.md for the steps.
//
//   node gen-nginx.js --host bridge-main.blumefi.com --nodes 5 > nginx-bridge-main.blumefi.com.conf
//
//   --host         the front door's hostname (required)
//   --nodes        how many nodes (required)
//   --public-base  first public TLS port, node i is base + i - 1 (default 8443)
//   --relay-base   first relay port on 127.0.0.1, node i is base + i - 1 (default 9081; mainnet beside dev: 9091)
//   --cert-name    the certbot lineage under /etc/letsencrypt/live/ (default: the host)
//   --acme-root    webroot for the challenge (default /var/www/html)
//   --acme-only    print only the port 80 block: the first file to install, so certbot can get the certificate that the TLS
//                  blocks need before nginx will load them
//   --ssl-options  a file nginx includes in every TLS block, for the protocol and cipher settings certbot keeps on the box
//                  (/etc/letsencrypt/options-ssl-nginx.conf, which the dev front door uses). Unset: nothing is added
//
// Beside another front door on the same box: server blocks that share a listen port are told apart by SNI (the
// server_name), so two hostnames may use the same public ports. The relay ports must differ.
const HOST_RE = /^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$/
const NAME_RE = /^[A-Za-z0-9][A-Za-z0-9._-]*$/
const PATH_RE = /^\/[A-Za-z0-9._/-]*$/

function int(value, what, min, max) {
  if (value === undefined) throw new Error(`${what} is required`)
  const text = String(value).trim()
  const n = Number(text)
  if (!/^[0-9]+$/.test(text) || n < min || n > max) throw new Error(`${what} must be a whole number from ${min} to ${max}, got '${value}'`)
  return n
}

function generate(opts) {
  const host = opts.host
  if (!host || !HOST_RE.test(host) || !host.includes(".")) throw new Error(`--host must be a hostname like bridge-main.blumefi.com, got '${host}'`)
  const acmeRoot = opts.acmeRoot ?? "/var/www/html"
  if (!PATH_RE.test(acmeRoot)) throw new Error(`--acme-root must be an absolute path, got '${acmeRoot}'`)

  const out = []
  if (opts.acmeOnly) {
    out.push(`# Port 80 only, for the first certificate for ${host}. Replace it with the full file (gen-nginx.js without --acme-only) once the certificate exists.`)
    out.push(`server {`)
    out.push(`    listen 80;`)
    out.push(`    server_name ${host};`)
    out.push(`    location /.well-known/acme-challenge/ { root ${acmeRoot}; }`)
    out.push(`    location / { return 404; }`)
    out.push(`}`)
    return out.join("\n") + "\n"
  }

  const nodes = int(opts.nodes, "--nodes", 1, 64)
  const publicBase = int(opts.publicBase ?? 8443, "--public-base", 1024, 65535)
  const relayBase = int(opts.relayBase ?? 9081, "--relay-base", 1024, 65535)
  if (publicBase + nodes - 1 > 65535 || relayBase + nodes - 1 > 65535) throw new Error(`${nodes} nodes do not fit above the base ports`)
  const lo = Math.max(publicBase, relayBase)
  const hi = Math.min(publicBase + nodes - 1, relayBase + nodes - 1)
  if (lo <= hi) throw new Error(`the public ports ${publicBase}-${publicBase + nodes - 1} and the relay ports ${relayBase}-${relayBase + nodes - 1} overlap`)
  const sslOptions = opts.sslOptions
  if (sslOptions !== undefined && !PATH_RE.test(sslOptions)) throw new Error(`--ssl-options must be an absolute path, got '${sslOptions}'`)
  const certName = opts.certName ?? host
  if (!NAME_RE.test(certName)) throw new Error(`--cert-name must be a plain name, got '${certName}'`)
  out.push(`# Browser front door for the bridge cluster at ${host}: ${nodes} node${nodes === 1 ? "" : "s"}. Generated by scripts/front-door/gen-nginx.js; regenerate, do not hand-edit.`)
  out.push(`# Valid TLS on ${publicBase}${nodes > 1 ? `-${publicBase + nodes - 1}` : ""} so hotpocket-js-client in a browser can connect. Each port proxies PLAIN WebSocket to the relay`)
  out.push(`# (relay.js, 127.0.0.1:${relayBase}${nodes > 1 ? `-${relayBase + nodes - 1}` : ""}), which dials the node's user port. Never point nginx's own TLS client at a node: hpws answers it about 4 times in 10.`)
  out.push(`# The node user ports stay local; only the public ports above are opened.`)
  out.push(`server {`)
  out.push(`    listen 80;`)
  out.push(`    server_name ${host};`)
  out.push(`    location /.well-known/acme-challenge/ { root ${acmeRoot}; }`)
  out.push(`    location / { return 404; }`)
  out.push(`}`)
  for (let i = 0; i < nodes; i++) {
    out.push(`server {`)
    out.push(`    listen ${publicBase + i} ssl;`)
    out.push(`    server_name ${host};`)
    out.push(`    ssl_certificate /etc/letsencrypt/live/${certName}/fullchain.pem;`)
    out.push(`    ssl_certificate_key /etc/letsencrypt/live/${certName}/privkey.pem;`)
    if (sslOptions) out.push(`    include ${sslOptions};`)
    out.push(`    location / {`)
    out.push(`        proxy_pass http://127.0.0.1:${relayBase + i}; # relay -> node ${i + 1}`)
    out.push(`        proxy_http_version 1.1;`)
    out.push(`        proxy_set_header Upgrade $http_upgrade;`)
    out.push(`        proxy_set_header Connection "Upgrade";`)
    out.push(`        proxy_set_header Host 127.0.0.1;`)
    out.push(`        proxy_read_timeout 3600s;`)
    out.push(`        proxy_send_timeout 3600s;`)
    out.push(`    }`)
    out.push(`}`)
  }
  return out.join("\n") + "\n"
}

function parseArgs(argv) {
  const opts = {}
  const names = { "--host": "host", "--nodes": "nodes", "--public-base": "publicBase", "--relay-base": "relayBase", "--cert-name": "certName", "--acme-root": "acmeRoot", "--ssl-options": "sslOptions" }
  for (let i = 0; i < argv.length; i += 2) {
    if (argv[i] === "--acme-only") {
      opts.acmeOnly = true
      i -= 1
      continue
    }
    const key = names[argv[i]]
    if (!key || argv[i + 1] === undefined) throw new Error(`unknown or incomplete argument '${argv[i]}': expected ${Object.keys(names).join(" ")} with a value, or --acme-only`)
    opts[key] = argv[i + 1]
  }
  return opts
}

module.exports = { generate, parseArgs }

if (require.main === module) {
  try {
    process.stdout.write(generate(parseArgs(process.argv.slice(2))))
  } catch (e) {
    console.error(`gen-nginx: ${e.message}`)
    process.exit(1)
  }
}
